// Problem: Merge Sorted Array
// Difficulty: EASY
// Link: https://leetcode.com/problems/merge-sorted-array/
// Approach: Two-pointer approach merging elements from the end of both `nums1`'s valid section and `nums2` into the end of `nums1` to prevent overwriting existing values.

class Solution {
public:
    void merge(vector<int>& nums1, int m, vector<int>& nums2, int n) {
        int p1 = m - 1;
        int p2 = n - 1;
        int p = m + n - 1;

        while (p1 >= 0 && p2 >= 0) {
            if (nums1[p1] >= nums2[p2]) {
                nums1[p] = nums1[p1];
                p1--;
            } else {
                nums1[p] = nums2[p2];
                p2--;
            }
            p--;
        }

        while (p2 >= 0) {
            nums1[p] = nums2[p2];
            p2--;
            p--;
        }
    }
};
